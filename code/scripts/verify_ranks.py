"""Independent audit of the ``Rank`` / ``#1`` columns printed by ``xc_big_tables.py``.

Why a separate script: the tables are generated by ``xc_paper_tables.ranks()``
and ``.wins()``; auditing those with the same functions proves nothing.  Here
the arithmetic is re-derived with a *different* implementation (numpy grouping
by value instead of a while-loop over the sorted list) and every printed cell
is compared against it.

Checks, in order:

1. direction  -- lower MSE/MAE must rank first; the per-dataset winner must be
   the minimum, never the maximum.  Also reports the winner and the spread per
   dataset, i.e. what "a good number" and "a bad number" look like here.
2. arithmetic -- ``Rank MSE``/``Rank MAE``/``Rank Σ``/``#1 *``/``Pos`` recomputed
   from scratch and diffed against the values the tables carry.
3. ties       -- the two metrics pick the same winner only on some datasets;
   prints where they disagree.
4. leverage   -- leave-one-dataset-out: with 8 core datasets each one carries
   1/8 of the mean rank, so this shows which dataset decides the answer and
   whether the ranking survives dropping any single one.

Run:  python scripts/verify_ranks.py [--json out.json]
"""
from __future__ import annotations

import sys
import json
import math
import argparse
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))

import xc_big_tables as BIG      # noqa: E402
import xc_paper_tables as PT     # noqa: E402

CORE = PT.CORE
DATASETS = PT.DATASETS


# --------------------------------------------------------------------------- #
# independent implementations
# --------------------------------------------------------------------------- #
def avg_rank(vals: dict) -> float:
    """Mean rank, 1 = smallest value, ties averaged.  numpy implementation."""
    names = [n for n, v in vals.items() if v is not None and not math.isnan(v)]
    v = np.array([vals[n] for n in names], dtype=float)
    if v.size == 0:
        return float('nan')
    # unique splits the ties; every member of a tie group gets the group's
    # mean position -- algebraically the same as the while-loop in PT.ranks
    uniq = np.unique(v)
    pos = np.empty(v.size, dtype=float)
    start = 0
    for u in uniq:
        k = int(np.count_nonzero(v == u))
        pos[start:start + k] = (start + start + k - 1) / 2.0 + 1.0
        start += k
    return float(pos.mean())


def rank_map(vals: dict) -> dict:
    """Rank one column: 1 = smallest, ties averaged.  numpy-bincount version.

    ``np.unique(..., return_inverse=True)`` labels each entry with its value
    group (ascending), so the mean position of a tie group is pure arithmetic
    on group counts -- no sorted-list walk, hence independent of PT.ranks().
    """
    names = [n for n, v in vals.items() if v is not None and not math.isnan(v)]
    if not names:
        return {}
    v = np.array([vals[n] for n in names], dtype=float)
    uniq, inv = np.unique(v, return_inverse=True)
    cnt = np.bincount(inv, minlength=uniq.size).astype(float)
    hi = np.cumsum(cnt)                     # last 1-based position of the group
    lo = hi - cnt + 1.0                     # first 1-based position
    avg = (lo + hi) / 2.0                   # mean position of the tie group
    return dict(zip(names, avg[inv].tolist()))


def ranks_of(rows: list, key: str, ds_list) -> dict:
    """Mean over datasets of the within-dataset rank (that is what Rank means)."""
    per = {r['name']: [] for r in rows}
    for d in ds_list:
        col = {r['name']: r[key].get(d) for r in rows}
        col = {n: v for n, v in col.items() if v is not None
               and isinstance(v, (int, float)) and not math.isnan(v)}
        for n, rk in rank_map(col).items():
            per[n].append(rk)
    return {n: (float(np.mean(v)) if v else float('nan')) for n, v in per.items()}


def wins_of(rows: list, key: str, ds_list) -> dict:
    out = {r['name']: 0 for r in rows}
    for d in ds_list:
        vals = {r['name']: r[key].get(d) for r in rows}
        vals = {n: v for n, v in vals.items() if v is not None
                and isinstance(v, (int, float)) and not math.isnan(v)}
        if not vals:
            continue
        best = min(vals.values())
        for n, v in vals.items():
            if abs(v - best) < 1e-12:
                out[n] += 1
    return out


def rank_map_tol(vals: dict, tol: float) -> dict:
    """Same as ``rank_map`` but differences smaller than ``tol`` (relative to
    the first member of the group) count as a tie.

    This is the "can the data tell these two apart?" question.  ``rank_map``
    breaks ties only at bit level (1e-12), so 0.3400 vs 0.3401 costs a whole
    rank.  With one seed and ~1% run-to-run noise on Type I, that is ranking
    noise, not ranking methods.
    """
    names = [n for n, v in vals.items() if v is not None and not math.isnan(v)]
    if not names:
        return {}
    v = np.array([vals[n] for n in names], dtype=float)
    order = np.argsort(v, kind='stable')
    sv = v[order]
    out = np.empty(v.size, dtype=float)
    start = 0
    for i in range(1, v.size + 1):
        if i == v.size or abs(sv[i] - sv[start]) > tol * max(abs(sv[start]), 1e-12):
            out[order[start:i]] = (start + i - 1) / 2.0 + 1.0
            start = i
    return dict(zip(names, out.tolist()))


def ranks_of_tol(rows: list, key: str, ds_list, tol: float) -> dict:
    per = {r['name']: [] for r in rows}
    for d in ds_list:
        col = {r['name']: r[key].get(d) for r in rows}
        col = {n: v for n, v in col.items() if v is not None
               and isinstance(v, (int, float)) and not math.isnan(v)}
        for n, rk in rank_map_tol(col, tol).items():
            per[n].append(rk)
    return {n: (float(np.mean(v)) if v else float('nan')) for n, v in per.items()}


def wins_of_tol(rows: list, key: str, ds_list, tol: float) -> dict:
    out = {r['name']: 0 for r in rows}
    for d in ds_list:
        vals = {r['name']: r[key].get(d) for r in rows}
        vals = {n: v for n, v in vals.items() if v is not None
                and isinstance(v, (int, float)) and not math.isnan(v)}
        if not vals:
            continue
        best = min(vals.values())
        for n, v in vals.items():
            if abs(v - best) <= tol * max(abs(best), 1e-12):
                out[n] += 1
    return out


def pos_of(rows: list, score: dict, tol: float = 1e-12) -> dict:
    order = sorted(rows, key=lambda r: (score[r['name']], r['name']))
    out, prev, prev_pos = {}, None, 0
    for i, r in enumerate(order):
        s = score[r['name']]
        if prev is not None and abs(s - prev) < tol:
            out[r['name']] = prev_pos
        else:
            out[r['name']] = i + 1
            prev_pos = i + 1
        prev = s
    return out


# --------------------------------------------------------------------------- #
def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--json', default=None)
    args = ap.parse_args()

    channel = PT.load_channel()
    bb = PT.load_channel_backbones()
    ours, fed, ref, _ctrl = BIG.channel_pool(channel, bb)
    pool = ours + fed + ref
    names = [r['name'] for r in pool]

    print(f'pool = {len(pool)} rows ({len(ours)} ours + {len(fed)} federated '
          f'+ {len(ref)} reference)')
    print(f'core  = {CORE}\n')

    # ---- 1. direction + what a good/bad number looks like --------------- #
    print('=' * 108)
    print('1. DIRECTION AND SPREAD  (lower is better on both metrics)')
    print('=' * 108)
    hdr = (f'{"dataset":<10} {"n":>3}  {"best":>8} {"who":<18} '
           f'{"median":>8} {"worst":>8} {"worst-who":<18} {"best/worst":>10}')
    print(hdr)
    for d in DATASETS:
        vals = {r['name']: r['mse'].get(d) for r in pool
                if r['mse'].get(d) is not None}
        vals = {n: v for n, v in vals.items() if not math.isnan(v)}
        if not vals:
            continue
        s = sorted(vals.items(), key=lambda kv: kv[1])
        bw, best = s[0]
        ww, worst = s[-1]
        med = float(np.median([v for _, v in s]))
        flag = '' if d in CORE else '   (excluded from core)'
        print(f'{d:<10} {len(s):>3}  {best:>8.4f} {bw:<18} '
              f'{med:>8.4f} {worst:>8.4f} {ww:<18} '
              f'{worst / best:>9.1f}x{flag}')

    # ---- 2. arithmetic -------------------------------------------------- #
    print()
    print('=' * 108)
    print('2. ARITHMETIC  (recomputed vs. what the tables carry)')
    print('=' * 108)
    my_rm = ranks_of(pool, 'mse', CORE)
    my_ra = ranks_of(pool, 'mae', CORE)
    my_wm = wins_of(pool, 'mse', CORE)
    my_wa = wins_of(pool, 'mae', CORE)
    my_rs = {n: my_rm[n] + my_ra[n] for n in names}
    my_ws = {n: my_wm[n] + my_wa[n] for n in names}
    my_pos = pos_of(pool, my_rs)

    bad = []
    for r in pool:
        n = r['name']
        for tag, mine, theirs, tol in (
                ('Rank MSE', my_rm[n], r['_rm'], 1e-9),
                ('Rank MAE', my_ra[n], r['_ra'], 1e-9),
                ('Rank Σ', my_rs[n], r['_rs'], 1e-9),
                ('#1 MSE', my_wm[n], r['_wm'], 0),
                ('#1 MAE', my_wa[n], r['_wa'], 0),
                ('#1 Σ', my_ws[n], r['_ws'], 0),
                ('Pos', my_pos[n], r['_rk_pos'], 0)):
            if abs(mine - theirs) > tol:
                bad.append((n, tag, mine, theirs))
    if bad:
        print('MISMATCH:')
        for row in bad:
            print('   ', row)
    else:
        print(f'OK -- all 7 columns x {len(pool)} rows match exactly.')

    # ---- 3. metric disagreement ---------------------------------------- #
    print()
    print('=' * 108)
    print('3. WHERE MSE AND MAE DISAGREE ON THE WINNER')
    print('=' * 108)
    same, diff = [], []
    for d in CORE:
        vm = {r['name']: r['mse'].get(d) for r in pool}
        va = {r['name']: r['mae'].get(d) for r in pool}
        vm = {n: v for n, v in vm.items() if v is not None and not math.isnan(v)}
        va = {n: v for n, v in va.items() if v is not None and not math.isnan(v)}
        bm = min(vm.values()); ba = min(va.values())
        wm = [n for n, v in vm.items() if abs(v - bm) < 1e-12]
        wa = [n for n, v in va.items() if abs(v - ba) < 1e-12]
        line = (f'{d:<10} MSE {bm:.4f} {",".join(wm):<26} '
                f'MAE {ba:.4f} {",".join(wa)}')
        (same if set(wm) == set(wa) else diff).append(line)
        print(line + ('' if set(wm) == set(wa) else '   <- differs'))
    print(f'\n{len(same)}/8 core datasets have the same winner on both metrics, '
          f'{len(diff)} differ.')

    # ---- 4. leverage ---------------------------------------------------- #
    print()
    print('=' * 108)
    print('4. LEAVE-ONE-DATASET-OUT  (does the Σ order survive dropping one?)')
    print('=' * 108)
    base_sorted = sorted(names, key=lambda n: (my_rs[n], n))
    base_pos = {n: i + 1 for i, n in enumerate(base_sorted)}
    focus = ['FedTDO-center', 'FedTDO-decorr', 'FedTDO-raw',
             'fedala', 'fedl2p', 'pfedcs', 'local', 'local+stmtm']
    focus = [f for f in focus if f in names]
    print(f'{"dropped":<10} ' + ' '.join(f'{f[:12]:>13}' for f in focus))
    print(f'{"(none)":<10} ' + ' '.join(f'{base_pos[f]:>13}' for f in focus))
    rows_out = []
    for d in CORE:
        sub = [x for x in CORE if x != d]
        rm = ranks_of(pool, 'mse', sub)
        ra = ranks_of(pool, 'mae', sub)
        rs = {n: rm[n] + ra[n] for n in names}
        p = pos_of(pool, rs)
        top = min(names, key=lambda n: (rs[n], n))
        delta = {f: p[f] - base_pos[f] for f in focus}
        print(f'-{d:<9} ' + ' '.join(
            f'{p[f]:>4}({delta[f]:+d})' if delta[f] else f'{p[f]:>7}   '
            for f in focus) + f'   | Σ1 = {top}')
        rows_out.append({'dropped': d, 'top': top,
                         'pos': {f: p[f] for f in focus},
                         'sigma': {f: round(rs[f], 3) for f in focus}})

    # ---- 5. how much of the order is real ------------------------------- #
    print()
    print('=' * 108)
    print('5. HOW MUCH OF THE ORDER SURVIVES NOISE  (relative tie tolerance)')
    print('=' * 108)
    print('"good" and "bad" only mean something if the pool can be separated. '
          'Below, two')
    print('numbers closer than `tol` are treated as a tie -- 0% is what the '
          'tables currently do.')
    print()
    print(f'{"tol":>6} {"Σ #1":<16} {"ctr Σ":>7} {"ctr Pos":>8} '
          f'{"decorr Σ":>9} {"decorr Pos":>10} {"fedala Σ":>9} '
          f'{"fedala Pos":>10} {"ctr #1Σ":>8}')
    band_out = []
    for tol in (0.0, 0.005, 0.01, 0.02, 0.05):
        rm = ranks_of_tol(pool, 'mse', CORE, tol)
        ra = ranks_of_tol(pool, 'mae', CORE, tol)
        wm = wins_of_tol(pool, 'mse', CORE, tol)
        wa = wins_of_tol(pool, 'mae', CORE, tol)
        rs = {n: rm[n] + ra[n] for n in names}
        ws = {n: wm[n] + wa[n] for n in names}
        p = pos_of(pool, rs, tol=0.05)
        top = min(names, key=lambda n: (rs[n], n))
        g = lambda n: (rs.get(n, float('nan')), p.get(n, -1), ws.get(n, 0))
        c, d_, f_ = g('FedTDO-center'), g('FedTDO-decorr'), g('fedala')
        print(f'{tol*100:>5.1f}% {top:<16} {c[0]:>7.2f} {c[1]:>8} '
              f'{d_[0]:>9.2f} {d_[1]:>10} {f_[0]:>9.2f} {f_[1]:>10} '
              f'{c[2]:>8}')
        band_out.append({'tol': tol, 'top': top,
                         'center': [round(c[0], 3), c[1], c[2]],
                         'decorr': [round(d_[0], 3), d_[1], d_[2]],
                         'fedala': [round(f_[0], 3), f_[1], f_[2]],
                         'sigma': {n: round(rs[n], 3) for n in names}})

    # ---- 6. separability per dataset ------------------------------------ #
    print()
    print('=' * 108)
    print('6. SEPARABILITY PER DATASET  (how much information a cell carries)')
    print('=' * 108)
    print('CV = spread of the 27 methods on that cell / its own level. A low CV '
          'means all')
    print('methods sit on top of each other, so whoever "wins" it won by noise.')
    print()
    print(f'{"dataset":<10} {"best":>8} {"median":>8} {"worst":>8} '
          f'{"spread":>8} {"CV":>7} {"top1 vs median":>14}  verdict')
    sep = []
    for d in DATASETS:
        vals = {r['name']: r['mse'].get(d) for r in pool}
        vals = {n: v for n, v in vals.items() if v is not None
                and not math.isnan(v)}
        a = np.array(list(vals.values()))
        best, med, worst = a.min(), float(np.median(a)), a.max()
        cv = float(a.std(ddof=1) / a.mean())
        spread = worst / best
        verdict = ('indistinguishable' if cv < 0.05 else
                   'weak' if cv < 0.15 else 'usable' if cv < 0.35 else 'loud')
        flag = '' if d in CORE else '  (not in core)'
        print(f'{d:<10} {best:>8.4f} {med:>8.4f} {worst:>8.4f} '
              f'{spread:>7.1f}x {cv:>7.3f} {100*(1-best/med):>13.1f}%  '
              f'{verdict}{flag}')
        sep.append({'dataset': d, 'cv': round(cv, 4), 'spread': round(spread, 3),
                    'in_core': d in CORE})

    if args.json:
        Path(args.json).write_text(json.dumps({
            'pool': names,
            'rank_mse': {n: round(my_rm[n], 4) for n in names},
            'rank_mae': {n: round(my_ra[n], 4) for n in names},
            'rank_sum': {n: round(my_rs[n], 4) for n in names},
            'wins_mse': my_wm, 'wins_mae': my_wa, 'pos': my_pos,
            'loo': rows_out,
            'noise_band': band_out,
            'separable': sep,
            'mismatch': bad,
        }, indent=2), encoding='utf-8')
        print(f'\nwrote {args.json}')

    print()
    print('=' * 108)
    print('VERDICT:', 'FAIL -- see mismatches above' if bad else
          'PASS -- rank/#1 arithmetic reproduces exactly')
    print('=' * 108)


if __name__ == '__main__':
    main()
